import assert from 'node:assert/strict';
import { mkdtempSync, mkdirSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
const file = new URL('../../desktop/storage-migration.mjs', import.meta.url);
assert.ok((await import('node:fs')).existsSync(file), 'game-owned migration implementation must exist');
const { discoverProfiles, gameKey, mergeStorage } = await import(file);
assert.equal(gameKey('sunset-coast-run.audio.v1'), true);
assert.equal(gameKey('sunset-coast-run.demo-a.settings'), true);
assert.equal(gameKey('sunset-coast-runner.secret'), false);
assert.equal(gameKey('unrelated.secret'), false);
const root = mkdtempSync(join(tmpdir(), 'velvet-discovery-'));
const profile = join(root, 'Prior Publisher', 'wrapper');
const db = join(profile, 'Local Storage', 'leveldb');
mkdirSync(db, { recursive: true });
writeFileSync(join(db, '000003.log'), Buffer.from('META:prior-game://game-20261009-93986676\0sunset-coast-run.audio.v1\0private-value'));
assert.deepEqual(discoverProfiles({ roots: [root], gameId: 'game-20261009-93986676', exclude: join(root, 'current') }).map(x => ({ profile: x.profile, origin: x.origin })), [{ profile, origin: 'prior-game://game-20261009-93986676' }]);
assert.equal(discoverProfiles({ roots: [root], gameId: 'other-game', exclude: '' }).length, 0);
writeFileSync(join(db,'000004.log'),'q'.repeat(512*1024));
const discoveryStart=performance.now();
assert.equal(discoverProfiles({ roots:[root], gameId:'game-20261009-93986676', exclude:'' }).length,1);
assert.ok(performance.now()-discoveryStart<2000,'opaque long values must not cause quadratic discovery');
const destination = { 'sunset-coast-run.audio.v1': 'new' };
const store = { getItem: k => destination[k] ?? null, setItem: (k, v) => destination[k] = v };
assert.deepEqual(mergeStorage(store, { 'sunset-coast-run.audio.v1': 'old', 'sunset-coast-run.records': 'records', 'foreign': 'secret' }), { copied: 1, preserved: 1 });
assert.equal(destination['sunset-coast-run.audio.v1'], 'new');
assert.equal(destination.foreign, undefined);
const { gameHandler } = await import('../../desktop/protocol.mjs');
writeFileSync(join(root,'index.html'),'game');
const handler=gameHandler(root,'velvet-game://game-20261009-93986676');
assert.equal((await handler(new Request('velvet-game://other-game/'))).status,404);
assert.equal((await handler(new Request('velvet-game://game-20261009-93986676/'))).status,200);
assert.equal((await handler(new Request('velvet-game://game-20261009-93986676/',{headers:{range:'bytes=1-2'}}))).status,206);
const { snappy } = await import('../../desktop/leveldb-keys.mjs');
// A six-byte back-reference proves discovery cannot rely on literal strings.
assert.equal(snappy(Buffer.from([12,20,...Buffer.from('abcdef'),22,6,0])).toString(),'abcdefabcdef');
assert.throws(()=>snappy(Buffer.from([12,22,6,0])));
console.log('Native migration ownership, discovery, and destination retention passed.');
